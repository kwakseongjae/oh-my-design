#!/usr/bin/env node
/**
 * build-presets-data.mjs — project the preset markdown catalog into machine-readable form.
 *
 * Markdown under skills/omd-autopilot/references/presets/ is the source of truth.
 * This writes two derived artifacts:
 *   - skills/omd-autopilot/references/presets/catalog.json  (consumed by `omd book`)
 *   - web/src/data/presets.generated.ts                     (consumed by the website)
 *
 * Usage: node scripts/build-presets-data.mjs [--check]
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const PRESET_DIR = join(ROOT, 'skills', 'omd-autopilot', 'references', 'presets');
const CATALOG_JSON = join(PRESET_DIR, 'catalog.json');
const WEB_DATA = join(ROOT, 'web', 'src', 'data', 'presets.generated.ts');

const LAYER_BY_DIR = {
  presets: 'fundamentals',
  primitives: 'primitives',
  genres: 'genres',
  flavors: 'flavors',
};

const GATE_RE = /\b(?:G|GS|C)\d+[a-z]?\b/g;

function listMarkdown(dir, group = 'presets') {
  const files = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      files.push(...listMarkdown(full, entry));
      continue;
    }
    if (!entry.endsWith('.md') || entry === 'INDEX.md') continue;
    files.push({ path: full, group, file: entry.replace(/\.md$/, '') });
  }
  return files;
}

function fieldFrom(body, label) {
  const line = body
    .split('\n')
    .find((l) => l.startsWith(`**${label}**`) || l.startsWith(`- **${label}**`));
  if (!line) return undefined;
  return line
    .replace(/^-?\s*\*\*[^*]+\*\*\s*(?:—|-|:)?\s*/, '')
    .trim() || undefined;
}

function summaryFrom(body) {
  const explicit = fieldFrom(body, '언제');
  if (explicit) return explicit;
  for (const block of body.split('\n\n')) {
    const text = block.trim();
    if (!text || text.startsWith('```') || text.startsWith('|')) continue;
    return text
      .replace(/\n/g, ' ')
      .replace(/\*\*/g, '')
      .replace(/`([^`]+)`/g, '$1')
      .slice(0, 400);
  }
  return '';
}

function parseFile({ path, group, file }) {
  const text = readFileSync(path, 'utf8');
  const lines = text.split('\n');
  const presets = [];
  let current;

  const flush = () => {
    if (!current) return;
    const body = current.bodyLines.join('\n').trim();
    presets.push({
      id: current.id,
      title: current.title,
      layer: LAYER_BY_DIR[group] ?? group,
      group: file,
      source: relative(ROOT, path),
      summary: summaryFrom(body),
      base: fieldFrom(body, 'Base'),
      accessibility: fieldFrom(body, '접근성'),
      tokenSlots: fieldFrom(body, '토큰 슬롯'),
      verified: fieldFrom(body, '검증'),
      gates: [...new Set(body.match(GATE_RE) ?? [])].sort(),
      body,
    });
    current = undefined;
  };

  for (const line of lines) {
    const heading = line.match(/^##\s+(P-[A-Z]{2}-[A-Za-z0-9-]+)\s+(.+)$/);
    if (heading) {
      flush();
      current = { id: heading[1], title: heading[2].trim(), bodyLines: [] };
      continue;
    }
    if (/^##\s/.test(line)) {
      flush();
      continue;
    }
    if (current) current.bodyLines.push(line);
  }
  flush();
  return presets;
}

function build() {
  const presets = listMarkdown(PRESET_DIR).flatMap(parseFile);
  const seen = new Map();
  for (const preset of presets) {
    if (seen.has(preset.id)) {
      throw new Error(`duplicate preset id ${preset.id} (${preset.source} and ${seen.get(preset.id)})`);
    }
    seen.set(preset.id, preset.source);
  }
  presets.sort((a, b) => a.id.localeCompare(b.id));

  const byLayer = {};
  for (const preset of presets) byLayer[preset.layer] = (byLayer[preset.layer] ?? 0) + 1;

  const catalog = {
    schema_version: '1',
    total: presets.length,
    by_layer: byLayer,
    presets,
  };

  const json = `${JSON.stringify(catalog, null, 1)}\n`;
  const ts = `// AUTO-GENERATED by scripts/build-presets-data.mjs — do not edit.\n`
    + `// Source of truth: skills/omd-autopilot/references/presets/*.md\n\n`
    + `export interface OmdPreset {\n`
    + `  id: string;\n  title: string;\n  layer: string;\n  group: string;\n  source: string;\n`
    + `  summary: string;\n  base?: string;\n  accessibility?: string;\n  tokenSlots?: string;\n`
    + `  verified?: string;\n  gates: string[];\n  body: string;\n}\n\n`
    + `export const PRESET_TOTAL = ${presets.length};\n\n`
    + `export const PRESETS_BY_LAYER: Record<string, number> = ${JSON.stringify(byLayer, null, 2)};\n\n`
    + `export const PRESETS: OmdPreset[] = ${JSON.stringify(presets, null, 2)};\n`;

  return { json, ts, total: presets.length, byLayer };
}

function main() {
  const check = process.argv.includes('--check');
  const { json, ts, total, byLayer } = build();

  if (check) {
    const currentJson = (() => { try { return readFileSync(CATALOG_JSON, 'utf8'); } catch { return ''; } })();
    const currentTs = (() => { try { return readFileSync(WEB_DATA, 'utf8'); } catch { return ''; } })();
    if (currentJson !== json || currentTs !== ts) {
      console.error('preset data is stale; run `node scripts/build-presets-data.mjs`.');
      process.exit(1);
    }
    console.log(`preset data current (${total} presets: ${JSON.stringify(byLayer)})`);
    return;
  }

  writeFileSync(CATALOG_JSON, json, 'utf8');
  writeFileSync(WEB_DATA, ts, 'utf8');
  console.log(`wrote ${relative(ROOT, CATALOG_JSON)} and ${relative(ROOT, WEB_DATA)} (${total} presets: ${JSON.stringify(byLayer)})`);
}

main();
