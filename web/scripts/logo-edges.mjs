// Logo silhouette colours (round 6). A logo "reads on its cap" through the colours that
// touch the cap, not through every fill: Mercari's white m sits on its own red box. This
// rasterises every variant in web/src/data/brand-svg.json (sharp, 512px on the long side),
// takes opaque pixels (alpha ≥ 230) within 2px of transparency (alpha ≤ 25) as the edge,
// snaps each to the nearest declared solid fill, and keeps fills with ≥ 1% of the edge (anti-aliasing noise drops out; a multi-colour mark made of small parts still counts).
// Output: web/src/data/brand-svg-edges.json, keyed by "/brand-svg/<id>/<variant>.svg".
// lib/landing-a/caps.ts checks these at 3:1 (falling back to every solid fill when a logo
// has no entry); __tests__/hero-logos.test.ts fails if a manifest variant is missing here.
//   node scripts/logo-edges.mjs
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
const require = createRequire(new URL("../package.json", import.meta.url));
const sharp = require("sharp");
const ROOT = new URL("..", import.meta.url).pathname;
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "src/data/brand-svg.json"), "utf8"));
const hex2 = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const fillsOf = (svg) => [...new Set([...svg.matchAll(/fill(?:="|:)\s*(#[0-9a-f]{3,6})\b/gi)].map((m) => {
  let h = m[1].toLowerCase();
  if (h.length === 4) h = "#" + [...h.slice(1)].map((c) => c + c).join("");
  return h;
}))];
const out = {};
for (const rec of manifest.records) for (const v of Object.values(rec.variants)) {
  const src = "/" + v.ref;
  const svg = fs.readFileSync(path.join(ROOT, "public", src), "utf8");
  // round 8: a shape with no fill paints black (the SVG default) — eslite's marks declare none;
  // white / black written as names count as those colours
  const named = [...svg.matchAll(/fill(?:="|:)\s*(white|black)\b/gi)].map((m) => (m[1].toLowerCase() === "white" ? "#ffffff" : "#000000"));
  let fills = [...new Set([...fillsOf(svg), ...named])];
  if (!fills.length && !/url\(#|<image\b/.test(svg)) fills = ["#000000"];
  if (!fills.length) { out[src] = { edge: [], note: "no solid fills (gradient or raster artwork)" }; continue; }
  const vb = svg.match(/viewBox="([^"]+)"/)?.[1].trim().split(/[\s,]+/).map(Number);
  const ratio = vb && vb[3] > 0 ? vb[2] / vb[3] : 1;
  const W = ratio >= 1 ? 512 : Math.round(512 * ratio), H = ratio >= 1 ? Math.round(512 / ratio) : 512;
  const sized = svg.replace(/<svg\b([^>]*)>/, (_m, a) => `<svg${a.replace(/\s(width|height)="[^"]*"/g, "")} width="${W}" height="${H}">`);
  const { data, info } = await sharp(Buffer.from(sized)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const a = (x, y) => (x < 0 || y < 0 || x >= info.width || y >= info.height ? 0 : data[(y * info.width + x) * 4 + 3]);
  const pal = fills.map(hex2), count = new Array(fills.length).fill(0);
  let n = 0;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    if (a(x, y) < 230) continue;
    let edge = false;
    for (let dy = -2; dy <= 2 && !edge; dy++) for (let dx = -2; dx <= 2; dx++) if (a(x + dx, y + dy) <= 25) { edge = true; break; }
    if (!edge) continue;
    const i = (y * info.width + x) * 4, c = [data[i], data[i + 1], data[i + 2]];
    let best = 0, bd = 1e9;
    pal.forEach((p, k) => { const d = (p[0] - c[0]) ** 2 + (p[1] - c[1]) ** 2 + (p[2] - c[2]) ** 2; if (d < bd) { bd = d; best = k; } });
    count[best]++; n++;
  }
  // round 8: a part drawn translucent (SAKURA's 40% petal) is skipped by the alpha ≥ 230 edge test,
  // yet it is what the cap shows through; such a logo is marked and caps.ts refuses it (fails closed)
  const translucent = /(?:^|[\s;"])(?:fill-)?opacity(?:="|:\s*)(?:0?\.\d+|0)\b/.test(svg);
  out[src] = { ...(translucent ? { translucent: true } : {}), edge: fills.filter((_, k) => n && count[k] / n >= 0.01), share: Object.fromEntries(fills.map((f, k) => [f, n ? +(count[k] / n).toFixed(3) : 0])) };
}
const file = path.join(ROOT, "src/data/brand-svg-edges.json");
fs.writeFileSync(file, JSON.stringify({ note: "Generated by web/scripts/logo-edges.mjs from brand-svg.json; do not edit by hand.", logos: out }, null, 1) + "\n");
for (const [k, v] of Object.entries(out)) console.log(k, JSON.stringify(v.edge), v.note ?? "");
